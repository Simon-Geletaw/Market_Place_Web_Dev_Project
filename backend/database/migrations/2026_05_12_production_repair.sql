-- Migration-safe production repair patch for existing MySQL databases.
-- Run after backend/database/schema.sql has already been imported.

USE market_place;

ALTER TABLE SERVICE_REQUESTS
    ADD COLUMN IF NOT EXISTS TITLE VARCHAR(160) NULL AFTER CATEGORY_ID,
    ADD COLUMN IF NOT EXISTS BUDGET DECIMAL(10, 2) NULL AFTER DESCRIPTION;

ALTER TABLE NOTIFICATIONS
    ADD COLUMN IF NOT EXISTS TYPE VARCHAR(50) DEFAULT 'general' AFTER USER_ID,
    ADD COLUMN IF NOT EXISTS LINK VARCHAR(500) NULL AFTER MESSAGE,
    ADD COLUMN IF NOT EXISTS ENTITY_TYPE VARCHAR(50) NULL AFTER LINK,
    ADD COLUMN IF NOT EXISTS ENTITY_ID CHAR(36) NULL AFTER ENTITY_TYPE;

CREATE TABLE IF NOT EXISTS PASSWORD_RESETS (
    RESET_ID CHAR(36) PRIMARY KEY,
    USER_ID CHAR(36) NOT NULL,
    TOKEN_HASH CHAR(64) NOT NULL UNIQUE,
    EXPIRES_AT TIMESTAMP NOT NULL,
    USED_AT TIMESTAMP NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_PASSWORD_RESETS_USER FOREIGN KEY (USER_ID) REFERENCES USERS (USER_ID) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE INDEX IF NOT EXISTS IDX_USERS_ROLE ON USERS (ROLE);
CREATE INDEX IF NOT EXISTS IDX_USERS_LOCATION ON USERS (LOCATION);
CREATE INDEX IF NOT EXISTS IDX_SERVICE_REQUESTS_STATUS ON SERVICE_REQUESTS (STATUS);
CREATE INDEX IF NOT EXISTS IDX_SERVICE_REQUESTS_CATEGORY ON SERVICE_REQUESTS (CATEGORY_ID);
CREATE INDEX IF NOT EXISTS IDX_SERVICE_REQUESTS_CUSTOMER ON SERVICE_REQUESTS (CUSTOMER_ID);
CREATE INDEX IF NOT EXISTS IDX_OFFERS_REQUEST ON OFFERS (REQUEST_ID);
CREATE INDEX IF NOT EXISTS IDX_OFFERS_PROVIDER ON OFFERS (PROVIDER_ID);
CREATE INDEX IF NOT EXISTS IDX_OFFERS_STATUS ON OFFERS (STATUS);
CREATE INDEX IF NOT EXISTS IDX_REVIEWS_PROVIDER ON REVIEWS (PROVIDER_ID);
CREATE INDEX IF NOT EXISTS IDX_AUDIT_LOGS_ACTION ON AUDIT_LOGS (ACTION);
CREATE INDEX IF NOT EXISTS IDX_STATUS_HISTORY_REQUEST ON STATUS_HISTORY (REQUEST_ID);
CREATE INDEX IF NOT EXISTS IDX_NOTIFICATIONS_USER_READ ON NOTIFICATIONS (USER_ID, IS_READ);
CREATE INDEX IF NOT EXISTS IDX_PASSWORD_RESETS_TOKEN ON PASSWORD_RESETS (TOKEN_HASH);
